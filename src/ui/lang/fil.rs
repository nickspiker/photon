// Pambalot na may kamalayan sa tanda para sa bihirang halagang may tanda (mga exit code ng tulay); walang tanda ang mga duodesimal na digit, nauuna ang minus.
fn fmt_i(n: i64) -> String {
    if n < 0 {
        format!("-{}", fmt_num((-n) as u32))
    } else {
        fmt_num(n as u32)
    }
}

