// Обёртка со знаком для редкого знакового значения (коды выхода моста); дюжинные цифры беззнаковые, минус едет впереди.
fn fmt_i(n: i64) -> String {
    if n < 0 {
        format!("-{}", fmt_num((-n) as u32))
    } else {
        fmt_num(n as u32)
    }
}

