// Enveloppe signée pour la rare valeur signée (codes de sortie du pont) ; les chiffres duodécimaux sont non signés, le moins passe devant.
fn fmt_i(n: i64) -> String {
    if n < 0 {
        format!("-{}", fmt_num((-n) as u32))
    } else {
        fmt_num(n as u32)
    }
}

// Le français élide « de » devant une voyelle, et un handle ou un nom d'appareil peut commencer par n'importe quelle lettre : la forme se choisit donc au rendu, jamais à l'écriture.
// Le h n'est pas élidé ici : muet ou aspiré est indécidable sur un nom arbitraire, et « de Hélène » se lit, alors que « d'Hollande » mal placé se remarque.
fn de(name: &str) -> String {
    let first = name.chars().next().unwrap_or(' ').to_lowercase().next().unwrap_or(' ');
    if matches!(first, 'a' | 'à' | 'â' | 'ä' | 'e' | 'é' | 'è' | 'ê' | 'ë' | 'i' | 'î' | 'ï' | 'o' | 'ô' | 'ö' | 'u' | 'ù' | 'û' | 'ü' | 'y') {
        format!("d\u{2019}{name}")
    } else {
        format!("de {name}")
    }
}

