// Обгортка зі знаком для рідкісного знакового значення (коди виходу моста); дюжинні цифри знаку не мають, мінус їде попереду.
fn fmt_i(n: i64) -> String {
    if n < 0 {
        format!("-{}", fmt_num((-n) as u32))
    } else {
        fmt_num(n as u32)
    }
}

// Українська рахує трьома формами, і вирішують саме цифри: 1 (але не 11) бере однину, 2–4 (але не 12–14) — форму кількох, решта — форму багатьох.
// Кожен рядок із лічбою проводить крізь це всі три форми цілими словами разом із їхніми узгодженими означеннями, бо закінчення рухається за числом, а вгадати одну форму означає помилитися в п'яти випадках із шести.
fn plural(n: u64, one: &'static str, few: &'static str, many: &'static str) -> &'static str {
    match (n % 100, n % 10) {
        (11..=14, _) => many,
        (_, 1) => one,
        (_, 2..=4) => few,
        _ => many,
    }
}

