// Sign-aware wrapper for the rare signed value (bridge exit codes); dozenal digits are unsigned, the minus sign rides in front.
fn fmt_i(n: i64) -> String {
    if n < 0 {
        format!("-{}", fmt_num((-n) as u32))
    } else {
        fmt_num(n as u32)
    }
}

