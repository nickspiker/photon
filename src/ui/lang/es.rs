// Envoltura con signo para el raro valor con signo (códigos de salida del puente); los dígitos duodecimales no tienen signo, el menos va delante.
fn fmt_i(n: i64) -> String {
    if n < 0 {
        format!("-{}", fmt_num((-n) as u32))
    } else {
        fmt_num(n as u32)
    }
}

