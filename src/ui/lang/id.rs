// Pembungkus sadar-tanda untuk nilai bertanda yang jarang muncul (kode keluar jembatan); digit duodesimal tidak bertanda, tanda minus berjalan di depan.
fn fmt_i(n: i64) -> String {
    if n < 0 {
        format!("-{}", fmt_num((-n) as u32))
    } else {
        fmt_num(n as u32)
    }
}

