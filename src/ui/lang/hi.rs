// चिह्न-सजग लपेट, उस विरले मान के लिए जिस पर चिह्न होता है (पुल के exit कोड); दर्जनी अंक बिना चिह्न के होते हैं, माइनस आगे चलता है।
fn fmt_i(n: i64) -> String {
    if n < 0 {
        format!("-{}", fmt_num((-n) as u32))
    } else {
        fmt_num(n as u32)
    }
}

