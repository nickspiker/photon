// Envoltório com sinal para o raro valor com sinal (códigos de saída da ponte); os dígitos duodecimais não têm sinal, o menos vai na frente.
fn fmt_i(n: i64) -> String {
    if n < 0 {
        format!("-{}", fmt_num((-n) as u32))
    } else {
        fmt_num(n as u32)
    }
}

