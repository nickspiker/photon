// Otoczka ze znakiem dla rzadkiej wartości ze znakiem (kody wyjścia mostu); cyfry dwunastkowe nie mają znaku, minus jedzie z przodu.
fn fmt_i(n: i64) -> String {
    if n < 0 {
        format!("-{}", fmt_num((-n) as u32))
    } else {
        fmt_num(n as u32)
    }
}

