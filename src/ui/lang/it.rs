// Involucro con segno per il raro valore con segno (codici di uscita del ponte); le cifre duodecimali sono senza segno, il meno passa davanti.
fn fmt_i(n: i64) -> String {
    if n < 0 {
        format!("-{}", fmt_num((-n) as u32))
    } else {
        fmt_num(n as u32)
    }
}

