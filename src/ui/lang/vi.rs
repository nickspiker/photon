// Vỏ bọc có dấu cho những giá trị hiếm hoi mang dấu (mã thoát của cầu nối); chữ số thập nhị phân không có dấu, dấu trừ đi trước.
fn fmt_i(n: i64) -> String {
    if n < 0 {
        format!("-{}", fmt_num((-n) as u32))
    } else {
        fmt_num(n as u32)
    }
}

