// Nadir görülen işaretli değer için (köprü çıkış kodları) işaret duyarlı sarmalayıcı; onikilik basamaklar işaretsizdir, eksi işareti önde gider.
fn fmt_i(n: i64) -> String {
    if n < 0 {
        format!("-{}", fmt_num((-n) as u32))
    } else {
        fmt_num(n as u32)
    }
}

